#!/usr/bin/env python3
"""Writes port/kz1hd/window_icon.h, the game window's icon as RGBA bytes, from the 64 px image of
installer/art/vekta.ico (the project's own art, made by tools/release/installer_art.py).

    python3 tools/icon_header.py [--check]

--check: exit 1 when the header is not what the .ico gives (tools/tests/test_window_icon.py runs it). Standard library
only: the .ico's 64 px entry is a 32-bit BMP (BGRA, bottom-up), which needs no image library.
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICO = os.path.join(ROOT, "installer", "art", "vekta.ico")
OUT = os.path.join(ROOT, "port", "kz1hd", "window_icon.h")
SIZE = 64


def rgba_from_ico(data, size=SIZE):
    """The size x size image of an .ico as RGBA bytes (rows top to bottom); ValueError when it has no 32-bit BMP of
    that size."""
    count = struct.unpack_from("<HHH", data, 0)[2]
    for i in range(count):
        w, h, _, _, _, bpp, length, off = struct.unpack_from("<BBBBHHII", data, 6 + 16 * i)
        if (w or 256) != size or (h or 256) != size or bpp != 32:
            continue
        hdr = data[off:off + 40]
        if hdr[:4] != b"(\0\0\0":
            raise ValueError(f"the {size} px image is not a BMP")
        _, bw, bh2, _, bits = struct.unpack_from("<IiiHH", hdr, 0)
        if bw != size or bh2 != 2 * size or bits != 32:
            raise ValueError(f"unexpected BMP header in the {size} px image")
        px = data[off + 40:off + 40 + size * size * 4]
        rows = [px[r * size * 4:(r + 1) * size * 4] for r in range(size)][::-1]   # bottom-up to top-down
        out = bytearray()
        for row in rows:
            for x in range(size):
                b, g, r, a = row[x * 4:x * 4 + 4]
                out += bytes((r, g, b, a))
        return bytes(out)
    raise ValueError(f"no 32-bit {size} px image in {ICO}")


def header(rgba, size=SIZE):
    lines = [f"/* The game window's icon: {size}x{size} RGBA, rows top to bottom (SDL_PIXELFORMAT_RGBA32).",
             " * Generated by tools/icon_header.py from installer/art/vekta.ico, the project's own art; do not edit. */",
             "#pragma once",
             "#include <stdint.h>",
             "",
             f"enum {{ KZ_WINDOW_ICON_SIZE = {size} }};",
             f"alignas(4) static const uint8_t kz_window_icon[{size * size * 4}] = {{"]
    for i in range(0, len(rgba), 24):
        lines.append("    " + ",".join(str(b) for b in rgba[i:i + 24]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    with open(ICO, "rb") as f:
        text = header(rgba_from_ico(f.read()))
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        print(f"icon_header: {OUT} {'current' if same else 'is stale (run python3 tools/icon_header.py)'}")
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"icon_header: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
