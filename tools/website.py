def json_ld(root, release):
    """Structured data (schema.org SoftwareApplication) for search engines: a data block, never run as script."""
    version = (root / "VERSION").read_text(encoding="utf-8").strip() if (root / "VERSION").is_file() else ""
    data = {"@context": "https://schema.org", "@type": "SoftwareApplication", "name": "Project Vekta",
            "description": META_DESC, "url": SITE_URL,
            "applicationCategory": "GameApplication", "operatingSystem": "Linux, Windows",
            "softwareVersion": version, "downloadUrl": REPO + "/releases", "codeRepository": REPO,
            "license": "https://opensource.org/licenses/MIT", "isAccessibleForFree": True, "image": SOCIAL[0],
            "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
            "author": {"@type": "Person", "name": "gustavomorinaga", "url": "https://github.com/gustavomorinaga"}}
    if not version:
        del data["softwareVersion"]
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return f"<script type=\"application/ld+json\">{text}</script>\n"




