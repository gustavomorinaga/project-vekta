def lint(page):
    """Problems with what a page would load: a script other than the same-origin site.js, inline scripts and event
    handlers, and resources from anywhere but the page itself and Google Fonts."""
    problems = []
    if re.search(r"\bon\w+\s*=|javascript:", page, re.I):
        problems.append("page contains an event handler or a javascript: URL")
    for m in re.finditer(r"<script\b([^>]*)>(.*?)</script>|<script\b[^>]*>", page, re.I | re.S):
        src = re.search(r"\bsrc=\"([^\"]+)\"", m.group(1) or "")
        if not src or src.group(1) != SCRIPT or (m.group(2) or "").strip():
            problems.append(f"page has an inline script or one that is not {SCRIPT}")
    for m in re.finditer(r"<(link|img|iframe|source|video|audio|embed|object)\b([^>]*)>", page, re.I):
        tag, attrs = m.group(1).lower(), m.group(2)
        if re.search(r'\brel="canonical"', attrs):
            continue
        for url in re.findall(r'\b(?:href|src|srcset)="([^"]+)"', attrs):
            url = url.split()[0]
            if re.match(r"[a-z]+:|//", url, re.I) and not ALLOWED_EXTERNAL.match(url):
                problems.append(f"<{tag}> loads {url} (only the page itself and Google Fonts are allowed)")
    if re.search(r"/home/|file:", page):
        problems.append("page contains a local path")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[1]), help="repository root")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = []
    page = render(root, problems)
    plain_page = render_plain(root, [])
    problems += lint(page) + ["plain.html: " + p for p in lint(plain_page)]
    outs = ((PAGE, page), (PLAIN, plain_page))
    if a.check:
        for rel, text in outs:
            f = root / rel
            if not f.exists():
                problems.append(f"{rel} missing (run python3 tools/website.py)")
            elif f.read_text(encoding="utf-8") != text:
                problems.append(f"{rel} is stale (run python3 tools/website.py)")
        for extra in ("style.css", "plain.css", SCRIPT):
            if not (root / "site" / extra).exists():
                problems.append(f"site/{extra} missing")
    if problems:
        for p in problems:
            print("website:", p, file=sys.stderr)
        return 1
    if not a.check:
        for rel, text in outs:
            (root / rel).write_text(text, encoding="utf-8")
    print(f"website: {'current' if a.check else 'wrote'} {PAGE} ({len(page)} bytes) and {PLAIN} "
          f"({len(plain_page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
