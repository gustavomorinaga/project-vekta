def td(label, cell):
    """A table cell with its column's name, which the phone layout shows above the cell (style.css, .tw td::before)."""
    return f"<td data-label=\"{esc(label)}\">{cell}</td>"


def table(rows, head):
    cols = ("Feature",) + tuple(head)
    o = ["<div class=\"tw\"><table>\n<thead><tr>" + "".join(f"<th>{esc(h)}</th>" for h in cols)
         + "</tr></thead>\n<tbody>\n"]
    for r in rows:
        if r["kind"] == "pc":   # the PC features: their default and where they are set
            cells = (inline(r["feature"]), inline(r["status"]), inline(r["evidence"], "docs/"))
        else:
            cells = ((inline(r["feature"]),) + ((inline(r["ps3"]),) if r["kind"] == "ps3" else ())
                     + (inline(detail(r), "docs/"), status_badge(r["status"])))
        o.append("<tr>" + "".join(td(h, c) for h, c in zip(cols, cells)) + "</tr>\n")
    o.append("</tbody></table></div>\n")
    return "".join(o)


