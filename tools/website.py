def lint(page):
    """Problems with what the page would load: scripts, and resources from anywhere but itself and Google Fonts."""
    problems = []
    if re.search(r"<script\b|\bon\w+\s*=|javascript:", page, re.I):
        problems.append("page contains a script or an event handler")
    for m in re.finditer(r"<(link|img|iframe|source|video|audio|embed|object)\b([^>]*)>", page, re.I):
        tag, attrs = m.group(1).lower(), m.group(2)
        if re.search(r'\brel="canonical"', attrs):
            continue
        for url in re.findall(r'\b(?:href|src|srcset)="([^"]+)"', attrs):
            url = url.split()[0]
            if re.match(r"[a-z]+:|//", url, re.I) and not ALLOWED_EXTERNAL.match(url):
                problems.append(f"<{tag}> loads {url} (only the page itself and Google Fonts are allowed)")
    if re.search(r"/home/|file:", page):
        problems.append("page contains a local path")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify instead of writing; exit 1 on any problem")
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[1]), help="repository root")
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)
    problems = []
    page = render(root, problems)
    problems += lint(page)
    out = root / PAGE
    if a.check:
        if not out.exists():
            problems.append(f"{PAGE} missing (run python3 tools/website.py)")
        elif out.read_text(encoding="utf-8") != page:
            problems.append(f"{PAGE} is stale (run python3 tools/website.py)")
        if not (out.parent / "style.css").exists():
            problems.append("site/style.css missing")
    if problems:
        for p in problems:
            print("website:", p, file=sys.stderr)
        return 1
    if not a.check:
        out.write_text(page, encoding="utf-8")
    print(f"website: {'current' if a.check else 'wrote'} {PAGE} ({len(page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
