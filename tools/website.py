def td(label, cell):
    """A table cell with its column's name, which the phone layout shows above the cell (style.css, .tw td::before)."""
    return f"<td role=\"cell\" data-label=\"{esc(label)}\">{cell}</td>"


def grid(caption, head, rows):
    """A table: `caption` (plain text, for screen readers; the heading or summary above already shows it), `head`
    [(column name as html, as plain text)] (a column without a name gets one for screen readers only), `rows` [[cell
    html]], the first cell of each row its header. The roles are written out because the phone layout (style.css,
    max-width 600px) turns the cells into blocks, and some browsers then stop reading it as a table."""
    o = [f"<div class=\"tw\"><table role=\"table\">\n<caption class=\"vh\">{esc(caption)}</caption>\n"
         "<thead role=\"rowgroup\"><tr role=\"row\">"]
    for i, (h, txt) in enumerate(head):
        name = h if txt.strip() else "<span class=\"vh\">" + esc("Item" if i == 0 else "Notes") + "</span>"
        o.append(f"<th role=\"columnheader\" scope=\"col\">{name}</th>")
    o.append("</tr></thead>\n<tbody role=\"rowgroup\">\n")
    for cells in rows:
        o.append(f"<tr role=\"row\"><th role=\"rowheader\" scope=\"row\">{cells[0]}</th>"
                 + "".join(td(txt, c) for (_h, txt), c in zip(head[1:], cells[1:])) + "</tr>\n")
    o.append("</tbody></table></div>\n")
    return "".join(o)


def table(rows, head, caption):
    cols = ("Feature",) + tuple(head)
    body = []
    for r in rows:
        if r["kind"] == "pc":   # the PC features: their default and where they are set
            body.append([inline(r["feature"]), inline(r["status"]), inline(r["evidence"], "docs/")])
        else:
            body.append([inline(r["feature"])] + ([inline(r["ps3"])] if r["kind"] == "ps3" else [])
                        + [inline(detail(r), "docs/"), status_badge(r["status"])])
    return grid(caption, [(esc(h), h) for h in cols], body)


def faq_entries(root, problems):
    """[(question, [paragraph])] from docs/FAQ.md: every "## " heading and the paragraphs under it."""
    text = read(root, FAQ_MD, problems)
    out = []
    for q, body in re.findall(r"^## (.+?)[ \t]*\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        paras = [" ".join(line.strip() for line in para.splitlines()) for para in re.split(r"\n\s*\n", body.strip())]
        out.append((q.strip(), [x for x in paras if x]))
    if text and not out:
        problems.append(f"{FAQ_MD}: no '## question' entries")
    return out


