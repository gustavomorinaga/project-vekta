def esc(s):
    return html.escape(s, quote=True)


def gh(path):
    return f"{REPO}/blob/main/{path}"


def inline(text, base=""):
    """A line of Markdown -> HTML: links (relative ones point at the file on GitHub, from the folder `base`), `code`,
    **bold**; everything else escaped."""
    out, pos = [], 0
    for m in re.finditer(r"`([^`]+)`|\[([^\]]+)\]\(([^)\s]+)\)|\*\*([^*]+)\*\*", text):
        out.append(esc(text[pos:m.start()]))
        if m.group(1) is not None:
            out.append(f"<code>{esc(m.group(1))}</code>")
        elif m.group(2) is not None:
            url = m.group(3)
            if not re.match(r"(https?:|mailto:|#)", url):
                path, _, frag = url.partition("#")
                path = pathlib.PurePosixPath(base, path).as_posix()
                while "/../" in "/" + path:   # docs/../README.md -> README.md
                    path = re.sub(r"(^|/)[^/]+/\.\./", r"\1", path, count=1)
                url = gh(path) + (f"#{frag}" if frag else "")
            out.append(f'<a href="{esc(url)}">{inline(m.group(2), base)}</a>')
        else:
            out.append(f"<strong>{inline(m.group(4), base)}</strong>")
        pos = m.end()
    out.append(esc(text[pos:]))
    return "".join(out)


def plain(text):
    """Markdown to plain text: links keep their words, code marks go."""
    return re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text).replace("`", "").replace("**", "")


def read(root, rel, problems):
    p = root / rel
    if not p.exists():
        problems.append(f"{rel} missing")
        return ""
    return p.read_text(encoding="utf-8")


def section(text, heading):
    m = re.search(r"^## " + re.escape(heading) + r"[ \t]*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    return m.group(1) if m else None


def table_rows(body):
    split = lambda line: [c.strip() for c in line.strip().strip("|").split("|")]  # noqa: E731
    return [split(line) for line in body.splitlines() if line.startswith("|") and not re.fullmatch(r"[|\s:-]+", line)]


def png_size(path):
    with open(path, "rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        return None
    return struct.unpack(">II", head[16:24])


def shots_found(root, problems):
    """[(YYYY-MM-DD, src, title, description, (w, h))] newest first, from every dated section of SCREENSHOTS.md: the
    caption under an image is its title, its alt text the description."""
    text = read(root, SHOTS_MD, problems)
    out = []
    for date, body in re.findall(r"^## (\d{4}-\d\d-\d\d)[ \t]*\n(.*?)(?=^## |\Z)", text, re.M | re.S):
        rows = table_rows(body)
        for i, cells in enumerate(rows):
            for j, cell in enumerate(cells):
                im = re.fullmatch(r"!\[([^\]]+)\]\(([^)]+)\)", cell)
                if not im:
                    continue
                below = rows[i + 1] if i + 1 < len(rows) else []
                title = below[j] if j < len(below) and not below[j].startswith("![") else ""
                src = (pathlib.PurePosixPath("docs") / im.group(2)).as_posix()
                if not title:
                    problems.append(f"{SHOTS_MD}: {src} has no caption under it")
                size = png_size(root / src) if (root / src).is_file() else None
                if size is None:
                    problems.append(f"{SHOTS_MD}: {src} is missing or not a PNG")
                    continue
                out.append((date, "../" + src, title, im.group(1), size))
    if not out and text:
        problems.append(f"{SHOTS_MD}: no screenshots in a '## YYYY-MM-DD' section")
    out.sort(key=lambda s: s[0], reverse=True)   # stable: the order within a day is the file's
    return out


HEADING = re.compile(r"## \[([^\]]+)\](?:[ \t]+-[ \t]+(\d{4}-\d\d-\d\d))?[ \t]*(?:\(([^)]*)\))?[ \t]*$")


def entries(root, problems):
    """The whole CHANGELOG, newest first: [{name, date, note, items: [(section, text)]}] for every '## [name] - DATE'
    heading ('## [Unreleased]' has date None). An item's wrapped lines are joined."""
    out, cur, sec = [], None, ""
    for line in read(root, CHANGELOG, problems).splitlines():
        m = HEADING.match(line)
        if m:
            cur = {"name": m.group(1), "date": m.group(2), "note": (m.group(3) or "").strip(), "items": []}
            out.append(cur)
            sec = ""
        elif cur is None:
            continue
        elif line.startswith("### "):
            sec = line[4:].strip()
        elif line.startswith("- "):
            cur["items"].append([sec, line[2:].strip()])
        elif line.startswith("  ") and line.strip() and cur["items"]:
            cur["items"][-1][1] += " " + line.strip()
    if not out:
        problems.append(f"{CHANGELOG}: no '## [name]' entries")
    return out


def clip(text, n=120):
    text = plain(text)
    return text if len(text) <= n else text[:n - 1].rsplit(" ", 1)[0].rstrip(",;:- ") + "..."


def changelog(log, n=CHANGELOG_N):
    """Newest-first [(date or None, entry name, text)]: each item cut at about 120 characters."""
    out = []
    for e in log:
        for _, t in e["items"]:
            out.append((e["date"], e["name"], clip(t)))
            if len(out) == n:
                return out
    return out


def todo(rows, n=TODO_N):
    """The next features not done yet, in table order: [(feature, status)]; the PS3 game's 'not yet' rows first, then
    its partial ones, then the port's own."""
    ps3 = [r for r in rows if r["kind"] == "ps3"]
    port = [r for r in rows if r["kind"] == "port"]
    pick = ([r for r in ps3 if r["status"] == "not yet"] + [r for r in ps3 if r["status"] == "partial"]
            + [r for r in port if r["status"] in ("not yet", "partial")])
    return [(r["feature"], r["status"]) for r in pick[:n]]


def status_badge(s):
    return f'<span class="st st-{STATUS_CLASS[s]}">{esc(LABEL[s])}</span>'


def detail(r):
    """A row's text after its status, as a sentence: '(FFmpeg)', ', at any window size', ': stereo, 5.1, 7.1'."""
    return r["detail"].lstrip(":, ").strip()


def divider(label):
    return f"<p class=\"divider\" aria-hidden=\"true\"><span>{esc(label)}</span></p>\n"


def more(href, label="More"):
    return f"<p class=\"more\"><a href=\"{esc(href)}\">{esc(label)}<span aria-hidden=\"true\"> &gt;</span></a></p>\n"


def long_date(d):
    y, m, dd = d.split("-")
    return f"{int(dd)} {MONTHS[int(m) - 1]} {y}"


def recomp(root, problems):
    m = re.search(r"ps3recomp (v\d+\.\d+\.\d+)", read(root, ".recomp.json", problems))
    if not m:
        problems.append(".recomp.json: no ps3recomp version")
    series = read(root, "port/patches/series", problems)
    return (m.group(1) if m else "?"), sum(1 for x in series.splitlines() if x.strip() and not x.startswith("#"))


def estimate(root, problems):
    body = section(read(root, ROADMAP, problems), "Progress") or ""
    m = re.search(r"\*\*about (\d+) % of the whole project\*\* and \*\*about (\d+) % of Killzone HD\*\*", body)
    if not m:
        problems.append(f"{ROADMAP}: the Progress section's estimate cannot be read")
        return "?", "?"
    return m.groups()


def requirements(root, problems):
    """(the '## Your game' text, the '## PC' table's header and rows: the first, Minimum and Tested columns)."""
    text = read(root, REQ, problems)
    game = section(text, "Your game")
    pc = section(text, "PC")
    if game is None or pc is None:
        problems.append(f"{REQ}: the '## Your game' or '## PC' section is missing")
        return "", [], []
    rows = table_rows(pc)
    if len(rows) < 2:
        problems.append(f"{REQ}: the PC section has no table")
        return "", [], []
    head = rows[0]
    try:
        idx = [0, head.index("Minimum"), head.index("Tested")]
    except ValueError:
        problems.append(f"{REQ}: the PC table lacks a Minimum or Tested column")
        return "", [], []
    body = [[r[i] for i in idx] for r in rows[1:] if len(r) == len(head)]
    return " ".join(game.split()), [head[i] for i in idx], body


def table(rows, head):
    o = ["<div class=\"tw\"><table>\n<thead><tr><th>Feature</th>"
         + "".join(f"<th>{esc(h)}</th>" for h in head) + "</tr></thead>\n<tbody>\n"]
    for r in rows:
        if r["kind"] == "pc":   # the PC features: their default and where they are set
            o.append(f"<tr><td>{inline(r['feature'])}</td><td>{inline(r['status'])}</td>"
                     f"<td>{inline(r['evidence'], 'docs/')}</td></tr>\n")
        else:
            ps3 = f"<td>{inline(r['ps3'])}</td>" if r["kind"] == "ps3" else ""
            o.append(f"<tr><td>{inline(r['feature'])}</td>{ps3}<td>{inline(detail(r), 'docs/')}</td>"
                     f"<td>{status_badge(r['status'])}</td></tr>\n")
    o.append("</tbody></table></div>\n")
    return "".join(o)


